/**
 * Post-build step:
 * 1. Renders every route (English + Hindi) to static HTML with its own <head>, so search engines,
 *    AI crawlers and link previews get full content without running JavaScript.
 * 2. Writes 404.html, sitemap.xml (with hreflang + images), robots.txt and llms.txt.
 * 3. Writes security headers for Netlify / Cloudflare Pages (_headers) and Apache / Hostinger (.htaccess).
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { securityHeaders } from '../security.config.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')
const ssrDir = path.join(root, 'dist-ssr')

const ssr = await import(pathToFileURL(path.join(ssrDir, 'entry-server.js')).href)
const siteUrl = ssr.SITE_URL
if (!/^https:\/\/[^/]+$/.test(siteUrl)) {
  throw new Error(`VITE_SITE_URL must be an https origin like https://www.example.com (got "${siteUrl}")`)
}

const template = await fs.readFile(path.join(dist, 'index.html'), 'utf8')
for (const marker of ['<!--head-->', '<div id="root"><!--app-html-->', '<html lang="en-IN">']) {
  if (!template.includes(marker)) throw new Error(`Marker ${marker} not found in dist/index.html`)
}

// data-path tells the browser which page this HTML was rendered for (see src/main.jsx).
const renderPage = (routePath) => {
  const { html, head, lang } = ssr.render(routePath)
  return template
    .replace('<html lang="en-IN">', `<html lang="${lang}">`)
    .replace('<!--head-->', head)
    .replace('<div id="root"><!--app-html-->', `<div id="root" data-path="${routePath}">${html}`)
}

// 1. Pages
let bytes = 0
for (const route of ssr.ROUTES) {
  const file = path.join(dist, route.path, 'index.html')
  const html = renderPage(route.path)
  bytes += Buffer.byteLength(html)
  await fs.mkdir(path.dirname(file), { recursive: true })
  await fs.writeFile(file, html)
}
await fs.writeFile(path.join(dist, '404.html'), renderPage(ssr.NOT_FOUND.path))

// 2. SEO files
const today = new Date().toISOString().slice(0, 10)
const altFor = (route, lang) => ssr.ROUTES.find((r) => r.page === route.page && r.param === route.param && r.lang === lang).path
const priority = { home: '1.0', cars: '0.9', car: '0.8', trips: '0.8', trip: '0.7', services: '0.8', contact: '0.8' }

const urls = ssr.ROUTES.map((route) => {
  const alternates = [
    ['en-IN', altFor(route, 'en')],
    ['hi-IN', altFor(route, 'hi')],
    ['x-default', altFor(route, 'en')],
  ]
    .map(([lang, p]) => `    <xhtml:link rel="alternate" hreflang="${lang}" href="${siteUrl}${p}" />`)
    .join('\n')
  return `  <url>
    <loc>${siteUrl}${route.path}</loc>
    <lastmod>${today}</lastmod>
    <priority>${priority[route.page] ?? '0.5'}</priority>
${alternates}
  </url>`
})

await fs.writeFile(
  path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`,
)

// AI search engines and assistants are explicitly welcome to read and cite the site.
const AI_BOTS = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Googlebot', 'Applebot', 'Applebot-Extended', 'Bingbot', 'meta-externalagent', 'Amazonbot', 'DuckAssistBot', 'MistralAI-User', 'CCBot']
await fs.writeFile(
  path.join(dist, 'robots.txt'),
  `User-agent: *
Allow: /

${AI_BOTS.map((bot) => `User-agent: ${bot}\nAllow: /`).join('\n\n')}

Sitemap: ${siteUrl}/sitemap.xml
`,
)

await fs.writeFile(path.join(dist, 'llms.txt'), ssr.buildLlmsTxt())

// 3. Security headers
const headers = Object.entries(securityHeaders())
await fs.writeFile(
  path.join(dist, '_headers'),
  `/*\n${headers.map(([k, v]) => `  ${k}: ${v}`).join('\n')}\n\n/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n\n/images/*\n  Cache-Control: public, max-age=2592000\n`,
)
await fs.writeFile(
  path.join(dist, '.htaccess'),
  `# Generated by scripts/prerender.mjs — edit security.config.js instead.
Options -Indexes
ServerSignature Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} off
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
</IfModule>

<IfModule mod_headers.c>
${headers.map(([k, v]) => `  Header always set ${k} "${v}"`).join('\n')}
  Header unset X-Powered-By
  <If "%{REQUEST_URI} =~ m#^/assets/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <If "%{REQUEST_URI} =~ m#^/images/#">
    Header set Cache-Control "public, max-age=2592000"
  </If>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript application/json image/svg+xml application/manifest+json application/xml
</IfModule>

AddType application/manifest+json .webmanifest
AddType image/avif .avif
AddType text/plain .txt
`,
)

await fs.rm(ssrDir, { recursive: true, force: true })
console.log(`✓ Pre-rendered ${ssr.ROUTES.length} pages (${(bytes / 1024 / 1024).toFixed(1)} MB) + 404 · sitemap.xml · robots.txt · llms.txt · _headers · .htaccess  (${siteUrl})`)
